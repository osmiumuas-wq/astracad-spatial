// Vite plugin: writes dist/sw.js, the service worker that lets the app load and run with no
// network. The worker's source embeds this build's file list and a version made from it, so a
// new deploy installs a new worker and replaces the old cache.
//
// Strategy:
//   - App shell (every built file except source maps and large optional downloads): cached at
//     install, served from the cache first. File names carry content hashes, so a cached file
//     is never stale.
//   - The page itself: network first (to pick up a new deploy), cache when offline.
//   - Large optional files (speech model, its runtime, the STEP reader): cached the first time
//     they are used, then served from the cache.
//   - Anything else (the co-design broker, other sites): not touched.
import { createHash } from 'node:crypto';

// The speech runtime is served from public/ort; the bundler also emits a copy that is never used.
const LAZY = [/\.map$/, /occt-import-js.*\.wasm$/, /ort-wasm.*\.wasm$/];

const source = (version, shell) => `// Generated by scripts/sw-plugin.mjs. Do not edit.
const VERSION = ${JSON.stringify(version)};
const SHELL = 'astra-shell-' + VERSION;
const LAZY = 'astra-lazy-v1';
const FILES = ${JSON.stringify(shell)};

self.addEventListener('install', (ev) => {
  ev.waitUntil(
    caches
      .open(SHELL)
      .then((c) => c.addAll(['./', ...FILES]))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (ev) => {
  ev.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('astra-shell-') && k !== SHELL).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

const lazy = (url) => /\\/(models|ort)\\//.test(url.pathname) || /occt-import-js.*\\.wasm$/.test(url.pathname);

self.addEventListener('fetch', (ev) => {
  const req = ev.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    ev.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(SHELL).then((c) => c.put('./', copy));
          return res;
        })
        .catch(() => caches.match('./', { cacheName: SHELL, ignoreVary: true }).then((r) => r || Response.error())),
    );
    return;
  }
  ev.respondWith(
    // ignoreVary: hosts send Vary: Origin, and module imports carry an Origin header that the
    // install-time requests did not, so a strict match would miss every cached script.
    caches.match(req, { ignoreSearch: true, ignoreVary: true }).then((hit) => {
      if (hit) return hit;
      return fetch(req).then((res) => {
        if (res.ok && lazy(url)) {
          const copy = res.clone();
          caches.open(LAZY).then((c) => c.put(req, copy));
        }
        return res;
      });
    }),
  );
});
`;

export function serviceWorker() {
  return {
    name: 'astra-service-worker',
    apply: 'build',
    generateBundle(_options, bundle) {
      const files = Object.keys(bundle)
        .filter((f) => !LAZY.some((re) => re.test(f)))
        .filter((f) => f !== 'index.html')
        .sort();
      // Public files that the app needs to start (scenes, panels); the speech model and its
      // runtime are large and optional, so they are cached on first use instead.
      const publicShell = ['scenes/main.iwsdk.scene.json'];
      const shell = [...files, ...publicShell].map((f) => './' + f);
      const version = createHash('sha256').update(shell.join('\n')).digest('hex').slice(0, 12);
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: source(version, shell) });
    },
  };
}
